import numpy as np
import matplotlib.pyplot as plt
import pandas as pd

# Parameter simulasi
T0 = 90       # Suhu awal kopi (°C)
Tr = 28       # Suhu ruangan (°C)
k = 0.08      # Konstanta pendinginan per menit

# Rentang waktu simulasi
waktu = np.linspace(0, 30, 7)

print("Suhu awal kopi:", T0, "°C")
print("Suhu ruangan:", Tr, "°C")
print("Konstanta pendinginan:", k)
print("Waktu simulasi:", waktu)

# Fungsi untuk menghitung suhu kopi
def suhu_kopi(t):
    T = Tr + (T0 - Tr) * np.exp(-k * t)
    return T

# Menghitung suhu pada setiap waktu
suhu = suhu_kopi(waktu)

# Menampilkan hasil
for t, T in zip(waktu, suhu):
    print(f"Menit ke-{t:.0f}: Suhu kopi = {T:.2f} °C")

# Membuat tabel hasil simulasi
data = {
    "Waktu (Menit)": waktu,
    "Suhu Kopi (°C)": suhu
}

tabel = pd.DataFrame(data)

# Menampilkan tabel
print("Tabel Hasil Simulasi Pendinginan Kopi")
display(tabel.round(2))

# Membuat grafik simulasi
plt.figure(figsize=(10, 6))

plt.plot(waktu, suhu, marker='o', linestyle='-', label='Suhu Kopi')

plt.axhline(y=Tr, linestyle='--', label='Suhu Ruangan (28°C)')

plt.title('Simulasi Pendinginan Kopi Panas')
plt.xlabel('Waktu (Menit)')
plt.ylabel('Suhu Kopi (°C)')

plt.grid(True)
plt.legend()

plt.show()